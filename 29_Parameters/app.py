def greet_user(first_name, last_name):       # the name in this case is a parameter
    print(f"Hi {first_name} {last_name}")
    print("Welcome Aboard")

greet_user("Youssef", "Mostafa")       # in this case we can put the name when we call the function. an       in our case the name we inserted is an argument.
greet_user("Mary", "Smith")
greet_user("Dark", "Side")